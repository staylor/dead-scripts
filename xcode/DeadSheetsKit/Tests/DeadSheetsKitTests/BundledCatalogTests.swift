import Foundation
import Testing
@testable import DeadSheetsKit

/// Checks the real `seeds.json` and the app's bundled files, which are generated outside Xcode.
struct BundledCatalogTests {
    let catalog = Catalog.bundled

    static let appResources = URL(filePath: #filePath)
        .deletingLastPathComponent()
        .deletingLastPathComponent()
        .deletingLastPathComponent()
        .deletingLastPathComponent()
        .appending(path: "leadsheets/Resources")

    static func exists(_ relativePath: String) -> Bool {
        FileManager.default.fileExists(atPath: appResources.appending(path: relativePath).path(percentEncoded: false))
    }

    @Test func loadsWithoutProblems() {
        #expect(!catalog.songs.isEmpty)
        #expect(catalog.problems == [])
    }

    @Test func everySongHasASheetAndCredits() {
        for song in catalog.songs {
            #expect(song.sheetFileName.hasSuffix(".pdf"), "\(song.id)")
            #expect(!song.credits.isEmpty, "\(song.id) has no writers")
            #expect(!song.lyrics.isEmpty, "\(song.id) has no lyrics")
        }
    }

    @Test func albumCoversExist() {
        for album in catalog.albums {
            guard let cover = album.coverFileName else {
                Issue.record("\(album.id) has no cover")
                continue
            }
            #expect(Self.exists("albums/\(cover)"), "albums/\(cover) is missing")
        }
    }

    @Test func artistAndSingerPhotosExist() {
        let photos = catalog.artists.compactMap(\.imageFileName) + catalog.singers.compactMap(\.imageFileName)
        for photo in photos {
            #expect(Self.exists("artists/\(photo)"), "artists/\(photo) is missing")
        }
    }

    @Test(.enabled(if: exists("pdfs"), "pdfs/ is generated by yarn xcode"))
    func everySheetHasAPDF() {
        for song in catalog.songs {
            #expect(Self.exists("pdfs/\(song.sheetFileName)"), "pdfs/\(song.sheetFileName) is missing")
        }
    }

    @Test(.enabled(if: exists("images"), "images/ is generated by convert_pdfs.swift"))
    func everySheetHasATVImage() {
        for song in catalog.songs {
            let image = (song.sheetFileName as NSString).deletingPathExtension + ".png"
            #expect(Self.exists("images/\(image)"), "images/\(image) is missing")
        }
    }
}
